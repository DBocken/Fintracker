/**
 * Blätter auf `string` geweitet — dieselbe Weitung wie `TranslationOverlay`
 * (`overlays/types.ts`), aus demselben Grund: `de` ist `as const`, seine
 * Blätter sind also String-LITERALE (`'Einrichtung'`). Ohne Weitung würde
 * `TranslationTree` genau DIESE deutschen Literalwerte verlangen — `en.ts`,
 * `ru.ts` und `tlh.ts` hätten dann (korrekterweise) andere Literale und wären
 * nicht zuweisbar. Gebraucht wird nur die STRUKTUR (welche Keys es gibt),
 * nicht der exakte deutsche Wortlaut.
 */
type Widen<T> = { [K in keyof T]: T[K] extends string ? string : Widen<T[K]> };

/** Form eines vollständigen Übersetzungsbaums — von `de` abgeleitet, der Referenzsprache. */
export type TranslationTree = Widen<typeof de>;
